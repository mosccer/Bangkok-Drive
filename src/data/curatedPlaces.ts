import type { PlaceCategory, PlaceSummary } from "../types";
import { getDistrictById } from "./bangkokDistricts";

const UPDATED_AT = "2026-05-30T00:00:00.000+07:00";

interface CuratedPlaceInput {
  id: string;
  nameTh: string;
  nameEn: string;
  category: PlaceCategory;
  lat: number;
  lng: number;
  districtId: string;
  rating?: number;
  userRatingCount?: number;
  tags: string[];
  curatedPriority: number;
}

function googleMapsSearchUri(name: string, lat: number, lng: number): string {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${name} ${lat},${lng}`)}`;
}

function curatedPlace(input: CuratedPlaceInput): PlaceSummary {
  const district = getDistrictById(input.districtId);
  if (!district) {
    throw new Error(`Unknown Bangkok district ${input.districtId}`);
  }

  return {
    ...input,
    source: "curated",
    name: input.nameEn,
    district: district.nameEn,
    districtName: district.nameEn,
    googleMapsUri: googleMapsSearchUri(input.nameEn, input.lat, input.lng),
    attributionRequired: false,
    updatedAt: UPDATED_AT,
  };
}

